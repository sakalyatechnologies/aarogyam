"""Aarogyam database design: the single source for docs/database.md and the schema explorer.

Edit this file, then run `python3 scripts/gen_schema_docs.py`.

Column syntax: "name type[?] [-> table] [| note]"
  ?          the column is nullable
  -> table   foreign key (clinic tables also include org_id in the key)
  | note     short explanation

Every table with rls="clinic" also has, without listing them here:
  org_id uuid -> organizations, id uuid (primary key is (org_id, id)),
  created_at, created_by, updated_at, updated_by, and deleted_at when lifecycle="soft_delete".
Tables with rls="global" have id uuid as primary key plus created_at / updated_at.

Status types such as org_status document their allowed values. In SQL they are text columns
with a CHECK constraint: Postgres enums can't use an index under row-level security.

lifecycle says how rows change; it drives columns, triggers, grants and CI checks:
  mutable      updated in place, never deleted
  soft_delete  updated in place, removed by setting deleted_at
  finalizable  editable until issued or signed, then frozen; corrections supersede
  append_only  inserted once, never updated or deleted
  ephemeral    may be hard-deleted (sessions, join rows, queues)
schema is the Postgres schema: "aarogyam" unless stated ("audit" for the two logs).
"""

