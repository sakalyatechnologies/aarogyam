#!/usr/bin/env node
// Generates the mouth art kit data in src/mouth-art/gen/ (one module per tooth type, per
// treatment model and per brushing band). Run: node web/packages/app-kit/scripts/gen-mouth-art.mjs
// The output is committed; never edit it by hand.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { TYPES } from './gen-mouth-art/types.mjs';
import { buildTooth } from './gen-mouth-art/tooth.mjs';
import { ellipse, mulberry32, compactPath } from './gen-mouth-art/geom.mjs';
import { buildShapes, buildStages } from './gen-mouth-art/stages.mjs';
import { buildBrushing } from './gen-mouth-art/brushing.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '../src/mouth-art/gen');
const HEADER = '// Generated by scripts/gen-mouth-art.mjs. Do not edit.\n';
const sizes = {};

// Replace repeated path strings with "@slot" references, then compact every path.
function dedupe(art) {
  const byD = new Map(Object.entries(art.geo).map(([k, v]) => [v, '@' + k]));
  for (const v of Object.values(art.views)) {
    const local = new Map(byD);
    for (const [k, d] of Object.entries(v.slots ?? {})) local.set(d, '@' + k);
    for (const l of v.layers) if (local.has(l.d)) l.d = local.get(l.d);
    for (const k of Object.keys(v.clips)) if (local.has(v.clips[k])) v.clips[k] = local.get(v.clips[k]);
  }
  return art;
}
function compactAll(o) {
  if (typeof o === 'string') return compactPath(o);
  if (Array.isArray(o)) return o.map(compactAll);
  if (o && typeof o === 'object') return Object.fromEntries(Object.entries(o).map(([k, v]) => [k, compactAll(v)]));
  return o;
}

function write(rel, body) {
  const file = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const text = HEADER + body;
  fs.writeFileSync(file, text);
  sizes[rel] = { raw: text.length, gz: zlib.gzipSync(text, { level: 9 }).length };
}

fs.rmSync(OUT, { recursive: true, force: true });

// Shared bone texture (one copy, imported by every tooth chunk).
const rnd = mulberry32(46);
let trab = '';
for (let i = 0; i < 42; i++) {
  const cx = rnd() * 104 - 2, cy = 82 + rnd() * 120, rx = 0.9 + rnd() * 2.2, ry = 0.7 + rnd() * 1.5;
  trab += ellipse(cx, cy, rx, ry);
}
write('textures.ts', `export const TRABECULAR = ${JSON.stringify(compactPath(trab))};\n`);

const keys = Object.keys(TYPES);
for (const key of keys) {
  const art = compactAll(dedupe(buildTooth(key, TYPES[key])));
  const json = JSON.stringify(art).replace('"__TEX__"', 'TRABECULAR');
  write(`teeth/${key}.ts`, `import type { ToothArt } from "../../types.js";\nimport { TRABECULAR } from "../textures.js";\n\nexport const art: ToothArt = ${json};\n`);
}

const shapes = compactAll(buildShapes());
write('shapes.ts', `import type { ShapeSet } from "../types.js";\n\nexport const SHAPES: ShapeSet = ${JSON.stringify(shapes)};\n`);

const stages = compactAll(buildStages());
for (const [model, set] of Object.entries(stages)) {
  write(`stages/${model}.ts`, `import type { StageSet } from "../../types.js";\n\nexport const stages: StageSet = ${JSON.stringify(set)};\n`);
}

const bands = compactAll(buildBrushing(TYPES));
for (const [band, data] of Object.entries(bands)) {
  write(`brushing/${band}.ts`, `import type { BrushingArt } from "../../types.js";\n\nexport const brushing: BrushingArt = ${JSON.stringify(data)};\n`);
}

fs.writeFileSync(path.join(OUT, 'sizes.json'), JSON.stringify(sizes, null, 2) + '\n');
const sum = (re) => Object.entries(sizes).filter(([k]) => re.test(k)).map(([k, v]) => `${k} ${(v.gz / 1024).toFixed(1)}K`).join(', ');
console.log('teeth:', sum(/^teeth/));
console.log('stages:', sum(/^stages/));
console.log('shared:', sum(/^(shapes|textures)/));
console.log('brushing:', sum(/^brushing/));
