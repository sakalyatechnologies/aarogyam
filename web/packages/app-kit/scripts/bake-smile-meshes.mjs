#!/usr/bin/env node
// Bakes the enamel shell of each permanent tooth type for the 3D smile (present-studio-design §6.4):
// real-teeth-3d `buildScene` (coarse), enamel layer only, positions int16 over the tooth's bounds, normals
// int8, indices delta-coded; written as one base64 module in src/present/smile3d-meshes.gen.ts.
// Run: node web/packages/app-kit/scripts/bake-smile-meshes.mjs   (output is committed; never edit by hand)
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PORTAL = path.resolve(HERE, '../../../apps/portal');
const { createServer } = await import(createRequire(path.join(PORTAL, 'package.json')).resolve('vite'));
const server = await createServer({ root: path.resolve(HERE, '..'), logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' });
const { resolveScene, buildScene, QUALITY } = await server.ssrLoadModule('/src/real-teeth-3d/index.ts');
// coarser cells than the detail view: about 4x fewer triangles, enough for a whole smile
QUALITY.coarse.tooth = Number(process.env.SMILE_H ?? 0.9);

const TYPES = ['u1', 'u2', 'u3', 'u4', 'u5', 'u6', 'u7', 'u8', 'l1', 'l2', 'l3', 'l4', 'l5', 'l6', 'l7', 'l8'];
const r = (n, d = 3) => Number(n.toFixed(d));
const out = {};
let tris = 0;
for (const type of TYPES) {
  const built = buildScene(resolveScene({ toothType: type }), 'coarse');
  const layer = built.parts.find((p) => p.name === 'tooth')?.layers.find((l) => l.kind === 'enamel');
  if (!layer) throw new Error(`no enamel for ${type}`);
  const { position, normal } = layer.mesh;
  const index = layer.outer ?? layer.mesh.index;
  const n = position.length / 3;
  const lo = [Infinity, Infinity, Infinity], hi = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < position.length; i++) { lo[i % 3] = Math.min(lo[i % 3], position[i]); hi[i % 3] = Math.max(hi[i % 3], position[i]); }
  const pos = new Int16Array(position.length);
  for (let i = 0; i < position.length; i++) pos[i] = Math.round(((position[i] - lo[i % 3]) / (hi[i % 3] - lo[i % 3] || 1)) * 65534 - 32767);
  const nor = new Int8Array(normal.length);
  for (let i = 0; i < normal.length; i++) nor[i] = Math.round(Math.max(-1, Math.min(1, normal[i])) * 127);
  const idx = new Int16Array(index.length);
  for (let i = 0, prev = 0; i < index.length; i++) {
    const d = index[i] - prev;
    if (d > 32767 || d < -32768) throw new Error(`index delta too wide for ${type}`);
    idx[i] = d;
    prev = index[i];
  }
  const bytes = Buffer.concat([Buffer.from(pos.buffer), Buffer.from(nor.buffer), Buffer.from(idx.buffer)]);
  out[type] = { n, t: index.length / 3, lo: lo.map((v) => r(v)), hi: hi.map((v) => r(v)), crown: built.crown.map((v) => r(v)), b: bytes.toString('base64') };
  tris += index.length / 3;
}
await server.close();
const file = path.resolve(HERE, '../src/present/smile3d-meshes.gen.ts');
fs.writeFileSync(file, `// Generated by scripts/bake-smile-meshes.mjs. Do not edit.\n// Per type: n vertices, t triangles, lo/hi bounds, crown centre, b = base64 of int16 xyz + int8 normals + int16 delta indices.\nexport interface BakedTooth { n: number; t: number; lo: number[]; hi: number[]; crown: number[]; b: string }\nexport const SMILE_MESHES: Record<string, BakedTooth> = ${JSON.stringify(out)};\n`);
console.log(`${TYPES.length} types, ${tris} triangles, ${fs.statSync(file).size} B, ${zlib.gzipSync(fs.readFileSync(file), { level: 9 }).length} B gz`);
